FULL = {'shadow', 'hope', 'flanders', 'road', 'sonnet18'}   # complete poems (no "From")
norm = lambda s: re.sub(r'\s+', ' ', re.sub(r'[^a-z0-9 ]', ' ', s.lower().replace('’', "'").replace('‘', "'").replace("'", ''))).strip()

errors, out = [], {}
for p in A:
    try:
        paras = ex(p['f'], p['start'], p['end'], p['poem'], p['nth'])
    except SystemExit as e:
        errors.append(f"{p['key']}: {e}"); continue
    if p.get('intro'): paras = [f"[{p['intro']}]"] + paras
    text = norm(' '.join(paras).replace('<em>', '').replace('</em>', ''))
    words = sum(len(x.split()) for x in paras)
    if words > 520: errors.append(f"{p['key']}: passage too long ({words} words)")
    for (q, a, wrong, why) in p['q']:
        if a in wrong: errors.append(f"{p['key']}: answer among wrong options: {q}")
        if len(set(wrong)) != 3: errors.append(f"{p['key']}: need 3 distinct wrong answers: {q}")
        # every quotation of 3+ words in the explanation must appear in the passage
        for quote in re.findall(r'“([^”]+)”|"([^"]+)"', why):
            quote = quote[0] or quote[1]
            for part in re.split(r'…|\s/\s|\.\.\.', quote):
                n = norm(part)
                if len(n.split()) >= 3 and n not in text:
                    errors.append(f"{p['key']}: quote not in passage: “{part.strip()}”")
    title = p['t'] if p['key'] in FULL else f"From {p['t']}"
    out[p['key']] = {'t': f"{title} ({p['year']})", 'by': p['by'], 'p': paras, **({'poem': True} if p['poem'] else {}),
                     'q': [[q, a, w, why] for (q, a, w, why) in p['q']]}
    print(f"{p['key']:12} {words:4} words  {len(p['q'])} questions")

if errors:
    print('\n'.join(['', 'ERRORS:'] + errors)); sys.exit(1)

